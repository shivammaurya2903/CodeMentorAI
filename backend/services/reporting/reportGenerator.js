/**
 * Report Generator Service
 * Exports comprehensive engineering assessment reports in Markdown format.
 */

function generateMarkdownReport({ repoId, scorecard, index }) {
  const dateStr = new Date().toLocaleDateString();

  return `# CodeMentorAI — Project Health & Engineering Report

**Repository:** \`${repoId || 'Workspace Repository'}\`  
**Generated On:** ${dateStr}  
**Overall Project Health Score:** **${scorecard?.overallScore || 0} / 100**

---

## 1. Executive Summary

CodeMentorAI performed a comprehensive multi-dimensional repository evaluation analyzing code structure, dependency manifests, security risks, performance benchmarks, test coverage, and architectural health.

- **Overall Health Score:** ${scorecard?.overallScore || 0}/100
- **Production Readiness:** ${scorecard?.scores?.productionReadiness || 0}/100
- **Total Files Analyzed:** ${index?.totalFiles || 0}
- **Detected Languages:** ${index ? Object.keys(index.languages).join(', ') : 'None'}

---

## 2. Dimensional Health Scorecard

| Dimension | Score | Assessment |
| :--- | :---: | :--- |
| **Security** | \`${scorecard?.scores?.security || 0}/100\` | Secret exposure & application security audit |
| **Code Quality** | \`${scorecard?.scores?.quality || 0}/100\` | Best practice compliance & linting |
| **Performance** | \`${scorecard?.scores?.performance || 0}/100\` | Event loop latency & resource efficiency |
| **Testing Maturity** | \`${scorecard?.scores?.testing || 0}/100\` | Automated test suite coverage |
| **Architecture** | \`${scorecard?.scores?.architecture || 0}/100\` | System layer isolation & modularity |
| **Maintainability** | \`${scorecard?.scores?.maintainability || 0}/100\` | Code duplication & naming consistency |
| **Reliability** | \`${scorecard?.scores?.reliability || 0}/100\` | Failure handling & resilience |
| **Production Readiness** | \`${scorecard?.scores?.productionReadiness || 0}/100\` | Deployment readiness |

---

## 3. Technology Stack & Architecture

\`\`\`
${scorecard?.archInfo?.diagram || 'No architecture diagram available.'}
\`\`\`

---

## 4. Top Actionable Recommendations ("Improve My Project")

${(scorecard?.topRecommendations || [])
  .map(
    (rec, i) => `
### ${i + 1}. [${rec.priority}] ${rec.title}

- **Category:** \`${rec.category}\`
- **Reason:** ${rec.reason}
- **Impact:** ${rec.impact}
- **Estimated Effort:** ${rec.effort}
`
  )
  .join('\n')}

---

## 5. Security & Risk Findings Summary

- **Critical Findings:** \`${scorecard?.findingsCount?.critical || 0}\`
- **High Severity:** \`${scorecard?.findingsCount?.high || 0}\`
- **Medium Severity:** \`${scorecard?.findingsCount?.medium || 0}\`

---
*Report automatically generated by CodeMentorAI Advanced Engineering Platform.*
`;
}

module.exports = { generateMarkdownReport };
